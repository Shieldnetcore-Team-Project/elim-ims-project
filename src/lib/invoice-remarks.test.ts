import { test } from "node:test";
import assert from "node:assert/strict";
import { visibleInvoiceRemarks } from "./invoice-remarks";

test("invoice remarks omit autogenerated dispatch posting references", () => {
  const remark = `2026-11-05: posted DSP-20261105-28150,
DSP-20261105-48326, DSP-20261105-99176,
DSP-20261105-09902, DSP-20261105-38202,
DSP-20261105-94399, DSP-20261105-23556,
DSP-20261105-14293, DSP-20261105-61038,
DSP-20261105-03151, DSP-20261105-12814,
DSP-20261105-32947, DSP-20261105-26048,
DSP-20261105-40656, DSP-20261105-99826,
DSP-20261105-16286, DSP-20261105-82143`;

  assert.equal(visibleInvoiceRemarks([remark]), null);
});

test("invoice remarks retain other notes and deduplicate them", () => {
  assert.equal(
    visibleInvoiceRemarks([
      "2026-11-05: posted DSP-20261105-28150",
      "Customer requested morning delivery",
      "Customer requested morning delivery",
      null,
    ]),
    "Customer requested morning delivery",
  );
});
